"""R2/R3 idempotency tests on the cu pipeline. No GPU, no network.

Uses a cu fixture video (sine audio + testsrc, generated by ffmpeg when
var/studio-fixture.mp4 is absent). Every step runs for cu through
LocalEngine: cu files on disk, cu hashes, cu invalidation.
"""
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from miro.studio.handlers import StudioHandlers
from miro.studio.store import IdempotentStore

FIXTURE = Path("C:/Miro/var/studio-fixture.mp4")


def make_handlers(tmp: Path) -> StudioHandlers:
    return StudioHandlers(root=tmp / "studio", store=IdempotentStore())


@pytest.fixture()
def video(tmp_path) -> str:
    if FIXTURE.is_file():
        dest = tmp_path / "fixture.mp4"
        shutil.copy2(FIXTURE, dest)
        return str(dest)
    dest = tmp_path / "fixture.mp4"
    subprocess.run(
        ["ffmpeg", "-y", "-v", "error",
         "-f", "lavfi", "-i", "sine=frequency=440:duration=4",
         "-f", "lavfi", "-i", "testsrc=size=320x240:rate=10:duration=4",
         "-c:v", "libx264", "-preset", "veryfast", "-c:a", "aac",
         "-shortest", str(dest)],
        check=True, timeout=120)
    return str(dest)


def test_r2_same_request_id_same_render_id(tmp_path, video):
    h = make_handlers(tmp_path)
    first = h.do_download(video, request_id="R2-req-1")
    # R2: retry with SAME request_id before seeing response
    retry = h.do_download(video, request_id="R2-req-1")
    assert first["render_id"] == retry["render_id"], "retry must return same render_id"
    assert retry["idempotent_replay"] is True
    assert first["video_id"] == retry["video_id"]


def test_r2_render_chain_idempotent(tmp_path, video):
    h = make_handlers(tmp_path)
    dl = h.do_download(video, request_id="R2-chain-dl")
    vid, rev = dl["video_id"], dl["revision"]
    tr = h.translate(vid, request_id="R2-chain-tr", expected_revision=rev,
                     default_voice="v")
    r1 = h.tts_mix_render(vid, request_id="R2-chain-render",
                          expected_revision=tr["revision"], default_voice="v")
    r2 = h.tts_mix_render(vid, request_id="R2-chain-render",
                          expected_revision=tr["revision"], default_voice="v")
    assert r1["render_id"] == r2["render_id"]
    assert r2["idempotent_replay"] is True
    assert Path(r1["output"]).is_file()  # cu file


def test_r3_stale_revision_rejected(tmp_path, video):
    h = make_handlers(tmp_path)
    dl = h.do_download(video, request_id="R3-dl")
    vid, rev = dl["video_id"], dl["revision"]
    tr = h.translate(vid, request_id="R3-tr", expected_revision=rev,
                     default_voice="v")
    try:
        # R3: stale expected_revision after concurrent edit
        h.save_segments(vid, [], request_id="R3-stale", expected_revision=rev)
        raise AssertionError("stale revision must raise 409")
    except ValueError as exc:
        assert getattr(exc, "status_code", None) == 409
    # fresh revision works
    ok = h.save_segments(vid, [], request_id="R3-fresh",
                         expected_revision=tr["revision"])
    assert ok["revision"] > tr["revision"]


def test_r3_editor_plan_local_no_llm(tmp_path, video):
    h = make_handlers(tmp_path)
    dl = h.do_download(video, request_id="R3-ed-dl")
    plan = h.editor_plan(dl["video_id"], "cat tu 2 den 4 giay, zoom",
                         request_id="R3-ed-plan", expected_revision=dl["revision"],
                         use_ai=False)  # local fallback, no LLM key needed
    assert plan["method"] == "Quy tac local"
    assert plan["plan"]["cuts"] and plan["plan"]["zooms"]
    assert plan["idempotent_replay"] is False
    replay = h.editor_plan(dl["video_id"], "cat tu 2 den 4 giay, zoom",
                           request_id="R3-ed-plan", expected_revision=dl["revision"],
                           use_ai=False)
    assert replay["render_id"] == plan["render_id"]
    assert replay["idempotent_replay"] is True
